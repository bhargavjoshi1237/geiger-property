import { TARGET, FILES, CONFLICT } from "./config.mjs";

const CHUNK = 250;
const quote = (s) => `'${String(s).replaceAll("'", "''")}'`;

function literal(v, type) {
  if (v === null || v === undefined) return "null";
  switch (type) {
    case "jsonb": return `${quote(JSON.stringify(v))}::jsonb`;
    case "_text": return v.length ? `array[${v.map(quote).join(", ")}]::text[]` : "'{}'::text[]";
    case "uuid":
    case "date":
    case "timestamptz": return `${quote(v)}::${type}`;
    case "bool": return v ? "true" : "false";
    case "int4":
    case "int8":
    case "numeric": return String(v);
    default: return quote(v);
  }
}

// One upsert per chunk: re-running the seed restores the demo rows in place.
function upsert(table, rows, cols) {
  const used = [...cols.keys()].filter((c) => rows.some((r) => c in r));
  const conflict = CONFLICT[table];
  const target = conflict?.target || "(id)";
  const update = (conflict?.update || used.filter((c) => c !== "id")).filter((c) => used.includes(c));
  const out = [];
  for (let i = 0; i < rows.length; i += CHUNK) {
    const values = rows
      .slice(i, i + CHUNK)
      .map((r) => `  (${used.map((c) => (c in r ? literal(r[c], cols.get(c).type) : "default")).join(", ")})`)
      .join(",\n");
    out.push(
      `insert into property.${table} (${used.join(", ")}) values\n${values}\n` +
        `on conflict ${target} do ${update.length ? `update set ${update.map((c) => `${c} = excluded.${c}`).join(", ")}` : "nothing"};`,
    );
  }
  return out.join("\n\n");
}

// Seed files (name → SQL) in FILES order. Tables with no FILES slot are reported.
export function emitFiles(db, schema) {
  const placed = new Set(FILES.flatMap(([, tables]) => tables));
  const unplaced = [...db.keys()].filter((t) => !placed.has(t) && db.get(t).length);
  const files = [];
  for (const [name, tables] of FILES) {
    const parts = [];
    let count = 0;
    for (const table of tables) {
      const rows = db.get(table) || [];
      if (!rows.length) continue;
      parts.push(`-- ${table} (${rows.length})\n${upsert(table, rows, schema.get(table))}`);
      count += rows.length;
    }
    if (!parts.length) continue;
    const header =
      `-- Demo project seed · ${name} · ${count} rows into project ${TARGET.projectId}.\n` +
      `-- GENERATED by supabase/seeds/demo_project/generate (npm run db:seed -- demo_project) — regenerate, don't hand-edit.\n`;
    // Inserts above fire record_event_trigger; those events are seed history, not work.
    const footer =
      `-- Events raised by this file's inserts are history, not work for the automation runner.\n` +
      `update property.automation_events set status = 'ignored', processed_at = now()\n` +
      `where project_id = '${TARGET.projectId}' and status = 'pending' and created_at = now();`;
    files.push({ name: `${name}.sql`, sql: `${header}\n${parts.join("\n\n")}\n\n${footer}\n`, count });
  }
  return { files, unplaced };
}
