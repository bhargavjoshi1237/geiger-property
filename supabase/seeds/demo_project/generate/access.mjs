import { permissionKeys } from "@geiger/rbac";

import rbacConfig from "@/geiger-rbac.config";
import { roleTables } from "@/lib/sandbox/seed/workspace";
import { SANDBOX_PREFIX, TARGET } from "./config.mjs";

// Demo access (PLAT-01h): public.roles and property.role_grants for the demo project, emitted as 06_access.sql.
// Roles are the playground's (the catalog's system roles plus a Regional manager). public.roles is suite-shared, so a role
// that already exists for the project (owner, admin, manager, viewer) keeps its name and other products' keys; only its
// Property keys are reset to the catalog. Grants go through property.rbac_ensure_membership as each organization member,
// the exact path their first visit takes (Owner for the org owner, Admin for role administrators, else Manager).

const quote = (s) => `'${String(s).replaceAll("'", "''")}'`;
const textArray = (list) => (list.length ? `array[${list.map(quote).join(", ")}]::text[]` : "'{}'::text[]");

// The demo's role rows: sandbox ids swapped for demo ids, keys checked against the catalog.
export function demoRoles(rows = roleTables().roles) {
  const keys = new Set(permissionKeys(rbacConfig));
  return rows.map((r) => {
    const unknown = r.permissions.filter((k) => k !== "*" && !keys.has(k));
    if (unknown.length) throw new Error(`role ${r.key}: keys not in the catalog: ${unknown.join(", ")}`);
    return { ...r, id: r.id.replace(SANDBOX_PREFIX, TARGET.idPrefix) };
  });
}

export function accessSql(roles = demoRoles(), target = TARGET) {
  const values = roles
    .map((r) =>
      [
        quote(target.projectId) + "::uuid",
        quote(r.key),
        quote(r.name),
        quote(r.description || ""),
        quote(r.color || "slate"),
        textArray(r.permissions),
        r.is_system ? "true" : "false",
        String(Number(r.sort) || 0),
        `${quote(JSON.stringify(r.metadata || {}))}::jsonb`,
        `${quote(target.createdBy)}::uuid`,
      ].join(", "),
    )
    .map((v) => `  (${v})`)
    .join(",\n");
  const org = quote(target.organizationId);
  return `-- public.roles (${roles.length}): Property's part of each role reset to the catalog; other products' keys, names and shared rows kept.
insert into public.roles as r (project_id, key, name, description, color, permissions, is_system, sort, metadata, created_by) values
${values}
on conflict (project_id, key) where key is not null and deleted_at is null do update set
  permissions = array(
    select t.k from unnest(array(select p from unnest(r.permissions) p where p not like 'property.%') || excluded.permissions)
      with ordinality t(k, n)
     group by t.k order by min(t.n)
  ),
  metadata = r.metadata || excluded.metadata;

-- property.role_grants: each member of the demo's organization gets the grant their first visit would mint.
do $$
declare
  v_user uuid;
begin
  for v_user in
    select o.owner from public.organizations o where o.id = ${org} and o.owner is not null
    union
    select o.created_by from public.organizations o where o.id = ${org} and o.created_by is not null
    union
    select ou."user" from public.organization_users ou where ou.organization = ${org} and ou."user" is not null
    union
    select m.value::uuid
      from public.organizations o,
           jsonb_array_elements_text(case when jsonb_typeof(o.metadata -> 'members') = 'array' then o.metadata -> 'members' else '[]'::jsonb end) m(value)
     where o.id = ${org} and m.value ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  loop
    perform set_config('request.jwt.claims', json_build_object('sub', v_user, 'role', 'authenticated')::text, true);
    perform property.rbac_ensure_membership(${quote(target.projectId)}::uuid);
  end loop;
  perform set_config('request.jwt.claims', '', true);
end $$;`;
}

// The 06_access seed file (name, sql, count) in emitFiles' shape.
export function accessFile(roles = demoRoles(), target = TARGET) {
  const header =
    `-- Demo project seed · 06_access · ${roles.length} roles and the organization's grants for project ${target.projectId}.\n` +
    `-- GENERATED by supabase/seeds/demo_project/generate (npm run db:seed -- demo_project) — regenerate, don't hand-edit.\n`;
  return { name: "06_access.sql", sql: `${header}\n${accessSql(roles, target)}\n`, count: roles.length };
}
