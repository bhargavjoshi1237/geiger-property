-- The project's Owner role ("*"), seeded when missing; internal to this file's functions.
create or replace function property.rbac_owner_role(p_project uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_role uuid;
begin
  select r.id into v_role from public.roles r
   where r.project_id = p_project and r.key = 'owner' and r.deleted_at is null
   limit 1;
  if v_role is null then
    insert into public.roles (project_id, key, name, description, color, permissions, is_system, sort, metadata)
    values (p_project, 'owner', 'Owner', 'Full access to everything, including billing.', 'violet', array['*'], true, 0,
            jsonb_build_object('key', 'owner'))
    on conflict (project_id, key) where key is not null and deleted_at is null do nothing
    returning id into v_role;
  end if;
  if v_role is null then
    select r.id into v_role from public.roles r
     where r.project_id = p_project and r.key = 'owner' and r.deleted_at is null
     limit 1;
  end if;
  return v_role;
end;
$$;
revoke all on function property.rbac_owner_role(uuid) from public, anon, authenticated;

-- One-shot translation of pre-01a settings keys to catalog keys; mirrors toPermissionKey() in lib/rbac.js.
create or replace function property.rbac_migrate_key(p_key text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when p_key = '*' then '*'
    when p_key = 'team.invite' then 'property.team.invite'
    when p_key = 'team.assign_roles' then 'property.team.assign'
    when p_key = 'roles.manage' then 'property.role.manage'
    when p_key = 'billing.manage' then 'property.billing.manage'
    when p_key = 'settings.manage' then 'property.settings.manage'
    when p_key = 'records.delete' then 'property.record.delete'
    when p_key = 'accounting.post' then 'property.accounting.post'
    when p_key = 'accounting.void' then 'property.accounting.void'
    when p_key = 'reports.export' then 'property.report.export'
    when p_key = 'reports.schedule' then 'property.report.schedule'
    when p_key = 'review.resolve' then 'property.review.resolve'
    when p_key = 'automations.manage' then 'property.automation.manage'
    when p_key = 'automations.run' then 'property.automation.run'
    when p_key ~ '^view\.[a-z0-9_]+$' then
      'property.' || case when substr(p_key, 6, 1) ~ '[0-9]' then 'page_' else '' end || substr(p_key, 6) || '.view'
    else null
  end;
