import { permissionKeys } from "@geiger/rbac";

// SQL copy of the catalog and system roles that property.rbac_ensure_membership seeds from on a project's first load.
// Generated from geiger-rbac.config.js (`npm run rbac:sql -- <migration>`); lib/rbac_sql.test.js fails when it drifts.

export const SQL_BEGIN = "-- rbac:system-roles:begin";
export const SQL_END = "-- rbac:system-roles:end";

const literal = (s) => `'${String(s).replace(/'/g, "''")}'`;

function textArray(values, indent) {
  if (!values.length) return "'{}'::text[]";
  const lines = [];
  for (let i = 0; i < values.length; i += 4) lines.push(values.slice(i, i + 4).map(literal).join(", "));
  return `array[\n${lines.map((l) => `${indent}  ${l}`).join(",\n")}\n${indent}]::text[]`;
}

// The generated block: property.rbac_catalog_keys() and property.rbac_system_role(text).
export function systemRolesSql(config) {
  const rows = config.systemRoles.map(
    (r) =>
      `    (${[r.key, r.name, r.description, r.color].map(literal).join(", ")}, ${Number(r.sort) || 0},\n     ${textArray(r.permissions, "     ")})`,
  );
  return [
    SQL_BEGIN,
    "-- Generated by `npm run rbac:sql` from geiger-rbac.config.js; regenerate rather than edit.",
    "create or replace function property.rbac_catalog_keys()",
    "returns text[]",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    `  select ${textArray(permissionKeys(config), "  ")};`,
    "$$;",
    "revoke all on function property.rbac_catalog_keys() from public, anon, authenticated;",
    "",
    "create or replace function property.rbac_system_role(p_key text)",
    "returns table (key text, name text, description text, color text, sort integer, permissions text[])",
    "language sql",
    "immutable",
    "set search_path = ''",
    "as $$",
    "  select t.key, t.name, t.description, t.color, t.sort, t.permissions",
    "  from (values",
    rows.join(",\n"),
    "  ) as t(key, name, description, color, sort, permissions)",
    "  where t.key = p_key;",
    "$$;",
    "revoke all on function property.rbac_system_role(text) from public, anon, authenticated;",
    SQL_END,
  ].join("\n");
}

// The generated block inside a migration's @up (null when it has none).
export function extractSystemRolesSql(migration) {
  const up = String(migration).replace(/\r\n/g, "\n").split(/^-- @down\s*$/m)[0];
  const start = up.indexOf(SQL_BEGIN);
  const end = up.indexOf(SQL_END, start);
  return start >= 0 && end > start ? up.slice(start, end + SQL_END.length) : null;
}

// The newest generated block across migration files ([{ name, sql }], any order).
export function latestSystemRolesSql(files) {
  const sorted = [...files].sort((a, b) => a.name.localeCompare(b.name));
  for (let i = sorted.length - 1; i >= 0; i -= 1) {
    const block = extractSystemRolesSql(sorted[i].sql);
    if (block) return { name: sorted[i].name, block };
  }
  return null;
}

// A regeneration migration: @up is the current block, @down puts the previous one back.
export function systemRolesMigration(config, previous) {
  return [
    "-- Rbac system roles",
    "--",
    "-- Regenerates property.rbac_catalog_keys() and property.rbac_system_role(text) from geiger-rbac.config.js",
    `-- (npm run rbac:sql). @down restores the copy from ${previous?.name || "nothing (drops both)"}.`,
    "",
    "-- @up",
    systemRolesSql(config),
    "",
    "-- @down",
    previous?.block ||
      "drop function if exists property.rbac_system_role(text);\ndrop function if exists property.rbac_catalog_keys();",
    "",
  ].join("\n");
}

// Whitespace-insensitive comparison, the way the migration ledger checksums SQL.
export const sameSql = (a, b) => String(a).replace(/\s+/g, " ").trim() === String(b).replace(/\s+/g, " ").trim();
